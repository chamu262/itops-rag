from __future__ import annotations

from pathlib import Path

import pytest

from itops_rag.loaders import load_path
from itops_rag.loaders.confluence import load_confluence_html
from itops_rag.loaders.markdown import load_markdown
from itops_rag.loaders.records import load_yaml_record
from itops_rag.loaders.tickets import load_ticket_csv, load_ticket_json
from tests.conftest import DEMO


def test_markdown_front_matter(tmp_path: Path) -> None:
    f = tmp_path / "rb.md"
    f.write_text(
        "---\nid: RB-1\ntitle: T\naccess: security\nupdated: 2026-01-02\ntags: [a, b]\n---\n# T\nbody\n"
    )
    (d,) = load_markdown(f, tmp_path)
    assert (d.id, d.access, d.updated, d.tags, d.source) == (
        "RB-1",
        "security",
        "2026-01-02",
        ["a", "b"],
        "rb.md",
    )


def test_markdown_without_front_matter_uses_h1(tmp_path: Path) -> None:
    f = tmp_path / "note-one.md"
    f.write_text("# My note\ntext")
    (d,) = load_markdown(f, tmp_path)
    assert d.title == "My note" and d.id == "NOTE-ONE" and d.access == "public"


def test_bad_access_is_rejected(tmp_path: Path) -> None:
    f = tmp_path / "x.md"
    f.write_text("---\naccess: everyone\n---\nx")
    docs, errors = load_path(tmp_path)
    assert not docs and "access" in errors[0]


def test_ticket_csv_drops_people_fields(tmp_path: Path) -> None:
    f = tmp_path / "t.csv"
    f.write_text(
        "key,summary,description,reporter,assignee_team,resolution,comments\n"
        'HELP-1,VPN down,"MG-401 seen",Jane Doe,Workplace Network,Reauth fixed it,"a || b"\n'
    )
    (d,) = load_ticket_csv(f, tmp_path)
    assert d.id == "HELP-1" and d.doc_type == "ticket" and d.access == "it-staff"
    assert "Jane Doe" not in d.text and "Reauth fixed it" in d.text and d.extra["redact_ip"]


def test_ticket_json(tmp_path: Path) -> None:
    f = tmp_path / "s.json"
    f.write_text(
        '{"records": [{"number": "INC1", "short_description": "SSO broken", "caller_id": "Jane",'
        ' "close_notes": "Re-uploaded cert", "work_notes": ["n1"]}]}'
    )
    (d,) = load_ticket_json(f, tmp_path)
    assert d.id == "INC1" and "Re-uploaded cert" in d.text and "Jane" not in d.text


def test_yaml_change_record(tmp_path: Path) -> None:
    f = tmp_path / "c.yaml"
    f.write_text(
        "id: CHG-1\ntitle: Rotate cert\nsystem: entra\nrisk: high\nstatus: rolled_back\n"
        "plan: [step one, step two]\nbackout: [undo]\nnew_field: kept\n"
    )
    (d,) = load_yaml_record(f, tmp_path)
    assert d.doc_type == "change" and "1. step one" in d.text and "## Backout" in d.text and "kept" in d.text


def test_confluence_strips_chrome(tmp_path: Path) -> None:
    f = tmp_path / "p.html"
    f.write_text(
        '<html><head><title>IT : Patching</title><meta name="itops:id" content="CF-9">'
        '<meta name="itops:access" content="it-staff"></head><body>'
        '<div id="breadcrumb-section"><a>IT</a><a>Standards</a></div><div id="main-header">Patching</div>'
        '<div id="main-content"><h2>SLA</h2><ul><li>Critical: 7 days</li></ul></div>'
        '<div id="footer">Document generated by Confluence</div></body></html>'
    )
    (d,) = load_confluence_html(f, tmp_path)
    assert d.id == "CF-9" and d.access == "it-staff" and d.title == "Patching"
    assert "## SLA" in d.text and "- Critical: 7 days" in d.text and "generated by Confluence" not in d.text
    assert d.extra["breadcrumb"] == "IT > Standards"


@pytest.mark.skipif(not DEMO.exists(), reason="demo corpus not present")
def test_demo_corpus_loads_cleanly() -> None:
    docs, errors = load_path(DEMO)
    assert errors == []
    types = {d.doc_type for d in docs}
    assert {"runbook", "kb", "ticket", "change", "postmortem"} <= types
    assert len(docs) > 100
    assert all(d.access in {"public", "it-staff", "security"} for d in docs)
